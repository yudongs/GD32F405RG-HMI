/**
 * @brief Draw BMP image - writes to framebuffer
 * @param x, y: top-left position
 * @param width: image width in pixels
 * @param high: image height in pixels
 * @param pstr: 1bpp image data (MSB first per byte)
 */
void ShowBMP(u8 x, u8 y, u8 width, u8 high, const u8 *pstr)
{
    u8 row, col;
    u8 bytes_per_row = (width + 7) / 8;
    for (row = 0; row < high; row++) {
        for (col = 0; col < width; col++) {
            u8 byte_val = pstr[row * bytes_per_row + (col / 8)];
            if (byte_val & (0x80 >> (col % 8))) {
                fb_set_pixel(x + col, y + row);
            } else {
                fb_clr_pixel(x + col, y + row);
            }
        }
    }
}

/**
 * @brief Draw solid line (Bresenham algorithm)
 */
void DrawLine(u32 x1, u32 y1, u32 x2, u32 y2)
{
    u32 temp;
    int dalt_x, dalt_y, err = 0;
    if (y1 > y2) {
        temp = x1;
        x1 = x2;
        x2 = temp;
        temp = y1;
        y1 = y2;
        y2 = temp;
    }
    Draw_Dot(x1, y1);
    dalt_x = x2 - x1;
    dalt_y = y2 - y1;
    if (dalt_x >= 0) {
        if (dalt_y > dalt_x) {  /* k > 1 */
            while (y1 < y2) {
                if (err < 0) {
                    x1 = x1 + 1;
                    y1 = y1 + 1;
                    err = err + dalt_y - dalt_x;
                } else {
                    y1 = y1 + 1;
                    err = err - dalt_x;
                }
                Draw_Dot(x1, y1);
            }
        } else {  /* 0 <= k <= 1 */
            if (dalt_y == 0)
                y1 = y1 - 1;
            while (x1 < x2) {
                if (err < 0) {
                    x1 = x1 + 1;
                    err = err + dalt_y;
                } else {
                    y1 = y1 + 1;
                    x1 = x1 + 1;
                    err = err + dalt_y - dalt_x;
                }
                Draw_Dot(x1, y1);
            }
        }
    } else {
        dalt_x = x1 - x2;
        if (dalt_y > dalt_x) {  /* k < -1 */
            while (y1 < y2) {
                if (err < 0) {
                    x1 = x1 - 1;
                    y1 = y1 + 1;
                    err = err + dalt_y - dalt_x;
                } else {
                    y1 = y1 + 1;
                    err = err - dalt_x;
                }
                Draw_Dot(x1, y1);
            }
        } else {  /* 0 > k >= -1 */
            if (dalt_y == 0)
                y1 = y1 - 1;
            while (x1 > x2) {
                if (err < 0) {
                    x1 = x1 - 1;
                    err = err + dalt_y;
                } else {
                    x1 = x1 - 1;
                    y1 = y1 + 1;
                    err = err + dalt_y - dalt_x;
                }
                Draw_Dot(x1, y1);
            }
        }
    }
}

