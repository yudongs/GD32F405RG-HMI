/**
 * @brief Write Instruction Code
 */
void wr_cmd(u8 cmd)
{
    LCD_DC_LOW();
    LCD_CS_LOW();
    spi_send_byte(cmd);
    LCD_CS_HIGH();
}

/**
 * @brief Write Display RAM Data
 */
void wr_dat(u8 dat)
{
    LCD_DC_HIGH();
    LCD_CS_LOW();
    spi_send_byte(dat);
    LCD_CS_HIGH();
}

/**
 * @brief Clear screen - clears framebuffer and flushes to LCD
 */
void ClrLcdram(void)
{
    FbClear();
    FlushToLCD();
}

/**
 * @brief ST7586 driver chip initialization
 */
void ST7586_initialize(void)
{
    /* LCD RESET */
    LCD_RST_HIGH();
    LCD_RST_LOW();
    delay_ms(10);
    LCD_RST_HIGH();
    delay_ms(500);

    /* read OPT data */
    wr_cmd(0xD7);
    wr_dat(0x9F);
    wr_cmd(0xE0);
    wr_dat(0x00);  /* OPT read enable */

    delay_ms(100);
    wr_cmd(0xE3);
    delay_ms(200);
    wr_cmd(0xE1);

    /* register initialization */
    wr_cmd(0x11);  /* exit sleep mode */
    delay_ms(50);

    wr_cmd(0xC0);  /* Set Vop - default contrast */
    wr_dat(0x44);  /* Vop7~Vop0 */
    wr_dat(0x01);  /* Vop8 */

    wr_cmd(0xC7);  /* Set Vop Offset */
    wr_dat(0x00);  /* Vop7~Vop0 */

    wr_cmd(0xC3);  /* Set Bias system */
    wr_dat(0x03);  /* 1/11 Bias */

    wr_cmd(0xC4);
    wr_dat(0x05);
    delay_ms(200);

    wr_cmd(0xD0);
    wr_dat(0x1D);
    wr_cmd(0xB5);
    wr_dat(0x8C);
    wr_cmd(0x38);

    wr_cmd(0x3A);  /* Enable DDRAM Interface */
    wr_dat(0x02);
    wr_cmd(0x36);  /* Set scan direction of COM and SEG */
    wr_dat(0xC8);  /* MY=1, MX=1 */

    wr_cmd(0xB0);  /* Set Duty */
    wr_dat(0x9F);

    wr_cmd(0xB1);  /* First Output Com */
    wr_dat(0x00);  /* Start line */

    wr_cmd(0x20);

    wr_cmd(0x37);
    wr_dat(0x00);

    wr_cmd(0xF4);  /* Temperature Gradient Compensation */
    wr_dat(0x99);  /* MT1=4, MT0=3 */
    wr_dat(0x52);  /* MT3=1, MT2=1 */
    wr_dat(0x08);  /* MT5=1, MT4=1 */
    wr_dat(0x04);  /* MT7=1, MT6=1 */
    wr_dat(0x00);  /* MT9=0, MT8=0 */
    wr_dat(0x00);  /* MTB=0, MTA=7 */
    wr_dat(0x9F);  /* MTD=8, MTV=0 */
    wr_dat(0xFF);  /* MTF=15, MTE=15 */

    wr_cmd(0x29);  /* Display On */

    FbClear();        /* clear framebuffer */
    FlushToLCD();     /* flush blank screen */
    LCD_BL_ON();      /* backlight on */
}

/**
 * @brief Turn LCD on/off
 */
void LcdOnOff(u8 onoff)
{
    if (onoff == 1)
        wr_cmd(0x29);  /* display on */
    else if (onoff == 0)
        wr_cmd(0x28);  /* display off */
}

/**
 * @brief Clear specified area in framebuffer and flush to LCD
 */
void ClrSpecifiedArea(u8 x1, u8 x2, u8 y1, u8 y2)
{
    u8 x, y;
    for (y = y1; y <= y2; y++) {
        for (x = x1; x <= x2; x++) {
            fb_clr_pixel(x, y);
        }
    }
    FlushToLCD();
}

